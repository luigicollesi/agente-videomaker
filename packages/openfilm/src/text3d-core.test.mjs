import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import * as THREE from 'three';
import {TextGeometry} from 'three/addons/geometries/TextGeometry.js';
import {FontLoader} from 'three/addons/loaders/FontLoader.js';
import {createText3DCore} from './text3d-core.mjs';
import {validateText3DInstance} from './text3d-contract.mjs';

test('v2 core composes native and external motion with deterministic seeks',async()=>{
 const raw=JSON.parse(await readFile(new URL('../node_modules/three/examples/fonts/helvetiker_regular.typeface.json',import.meta.url),'utf8'));
 const font=new FontLoader().parse(raw);
 const calls=[];
 class FakeRenderer{
  isWebGLRenderer=true;
  setSize(){} setClearColor(){} render(){calls.push('render')} dispose(){calls.push('dispose')}
 }
 const adapter={...THREE,TextGeometry,WebGLRenderer:FakeRenderer};
 let disposed=0,ownedDisposed=0;
 const component=createText3DCore({THREE:adapter,canvas:{width:960,height:540},font,text:'A',
  native:[{evaluate(time,{model}){model.characters[0].position.y+=time}}], 
  appearance:[{evaluate(time,{materials,scene,resources}){materials[0].color.setRGB(time/10,0,0);materials[0].emissiveIntensity=time;scene.children.find(x=>x.isDirectionalLight).intensity=time;resources.track(this.resource??=( {dispose(){ownedDisposed++}} ));},dispose(){disposed++}}]});
 assert.deepEqual(validateText3DInstance(component),[]);
 await component.frame(2);
 const first=component.model.characters[0].position.y;
 const firstColor=component.appearance.materials[0].color.r;
 const firstEmissive=component.appearance.materials[0].emissiveIntensity;
 await component.frame(1);
 await component.frame(2);
 assert.equal(component.model.characters[0].position.y,first);
 assert.equal(component.appearance.materials[0].color.r,firstColor);
 assert.equal(component.appearance.materials[0].emissiveIntensity,firstEmissive);
 assert.equal(calls.filter(x=>x==='render').length,3);
 const originalRenderer=component.renderer;
 assert.throws(()=>createText3DCore({THREE:adapter,canvas:{width:960,height:540},font,text:'A',native:[{channels:['material.color'],evaluate(){}}],appearance:[{channels:['material.color'],evaluate(){}}]}),/Conflicting Text3D channel/);
 component.setText('ABC');
 assert.equal(component.renderer,originalRenderer);
 assert.equal(component.model.meshes.length,3);
 await component.frame(2);
 const newBaseline=component.model.root.position.x;
 await component.frame(1);
 await component.frame(2);
 assert.equal(component.model.root.position.x,newBaseline);
 component.setText('TESTEEEEE');
 assert.equal(component.model.characters.length,9);
 assert.equal(component.renderer,originalRenderer);
 const fitScale=component.model.root.parent.scale.x;
 assert.ok(fitScale>0&&fitScale<=1,'auto-fit scale should remain positive and not enlarge');
 assert.ok(component.appearance.lights[0].intensity<=1,'ambient light should not wash out neon colors');
 assert.ok(component.appearance.lights[1].intensity<=1.5,'key light should preserve saturated color');
 component.setTypography({font,fontSize:.62,letterSpacing:.08,textAlign:'right'});
 assert.equal(component.renderer,originalRenderer);
 assert.equal(component.model.meshes[0].geometry.parameters.options.size,.62);
 assert.equal(component.model.characters.length,9);
 assert.throws(()=>component.setTypography({fontSize:-1}),/font size/);
 component.setRotation(25,-40);
 assert.equal(component.renderer,originalRenderer);
 const angle=component.model.root.parent.rotation.y;
 await component.frame(2);await component.frame(1);
 assert.equal(component.model.root.parent.rotation.y,angle);
 assert.throws(()=>component.setRotation(NaN,0),/rotation/);
 component.setViewport({x:120,y:80,width:360,height:190});
 assert.equal(component.renderer,originalRenderer);
 await component.frame(1);
 const fullStageCenter=component.model.root.parent.parent.position.clone();
 assert.ok(Math.abs(fullStageCenter.x)>0.001||Math.abs(fullStageCenter.y)>0.001);
 assert.throws(()=>component.setViewport({x:0,y:0,width:-1,height:10}),/viewport/);
 component.setViewport(null);
 component.setDepth(0.9);
 assert.ok(component.model.meshes[0].geometry.parameters.options.depth===0.9);
 assert.equal(component.renderer,originalRenderer);
 component.resize(584,291);
 await component.frame(2);
 assert.ok(component.model.root.parent.scale.x>0);
 component.dispose();component.dispose();
 assert.equal(disposed,1);
 assert.equal(ownedDisposed,1);
 assert.equal(calls.filter(x=>x==='dispose').length,1);
 await assert.rejects(component.frame(2),/disposed/);
});
